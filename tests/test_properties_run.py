@st.composite
def cumulative_scenarios(draw):
    """A failure-free grid and a scripted answer text for every (persona, item)."""
    grid = draw(grids(failures=False))
    script = {(j, i): draw(rich_text) for j in range(grid.n_personas) for i in range(grid.n_items)}
    return grid, script


class TestCumulativeMode:
    @PROFILE
    @given(scenario=cumulative_scenarios(), workers=concurrency)
    def test_any_answer_text_is_remembered_literally_and_never_breaks_a_run(
        self, scenario, workers
    ):
        grid, script = scenario
        _, summary, _, _ = run_and_check(
            grid, cumulative=True, max_concurrency=workers, script=script
        )
        assert summary.n_failed == 0

    @PROFILE
    @given(scenario=cumulative_scenarios(), workers=concurrency)
    def test_a_later_prompt_contains_the_earlier_answers_of_its_persona_only(
        self, scenario, workers
    ):
        grid, script = scenario
        # make every answer identifiable: tag it with the persona and item it belongs to
        tagged = {(j, i): f"\xab{j}.{i}\xbb{text}" for (j, i), text in script.items()}
        experiment, models = build_experiment(grid, script=tagged)
        experiment.run(
            cumulative=True, max_concurrency=workers, on_error="ignore", show_progress=False
        )
        for model in models.values():
            for _seed, persona, item, prompt in model.calls:
                for other_persona in range(grid.n_personas):
                    for earlier in range(grid.n_items):
                        answer = tagged[(other_persona, earlier)]
                        remembered = other_persona == persona and earlier < item
                        assert (answer in prompt) is remembered, (persona, item, answer)

    @PROFILE
    @given(grid=grids(failures=False))
    def test_the_first_question_of_a_persona_is_asked_like_in_a_plain_run(self, grid):
        plain_experiment, plain_models = build_experiment(grid)
        plain_experiment.run(show_progress=False)
        memory_experiment, memory_models = build_experiment(grid)
        memory_experiment.run(cumulative=True, show_progress=False)
        for model_id in grid.models:
            first_questions = {
                (seed, persona): prompt
                for seed, persona, item, prompt in plain_models[model_id].calls
                if item == 0
            }
            remembered = {
                (seed, persona): prompt
                for seed, persona, item, prompt in memory_models[model_id].calls
                if item == 0
            }
            assert remembered == first_questions

    @PROFILE
    @given(grid=grids(), workers=concurrency)
    def test_a_failed_answer_is_not_remembered(self, grid, workers):
        experiment, models = build_experiment(grid)
        experiment.run(
            cumulative=True, max_concurrency=workers, on_error="ignore", show_progress=False
        )
        for model in models.values():
            # a remembered failure would read "... ->" followed by "None" in a later prompt
            assert not any("-> None" in prompt for _, _, _, prompt in model.calls)


def test_further_messages_of_the_template_survive_in_cumulative_mode():
    grid = Grid(
        n_items=2,
        n_personas=1,
        seeds=("1",),
        models=("m",),
        item_options=(None, None),
        failing=(frozenset(),),
    )
    priming = [{"role": "ai", "content": "My answer is:"}]
    first_prompts = {}
    for cumulative in (False, True):
        experiment, models = build_experiment(grid, trailing=priming)
        try:
            experiment.run(cumulative=cumulative, show_progress=False)
        except ValueError:
            assert cumulative  # refusing a template that cumulative mode cannot honour is fine
            return
        first_prompts[cumulative] = models["m"].calls[0][3]
    assert first_prompts[True] == first_prompts[False]


