class ModelDown(RuntimeError):
    """The error the scripted model raises."""


class ScriptedLLM(LLM):
    """Deterministic fake model.

    Its answer is a pure function of ``(tag, seed, prompt)``, or - if ``script`` is given - the
    scripted text of the (persona, item) it recognises in the prompt. It records every prompt,
    can fail for chosen personas and can sleep a prompt-dependent time to scramble the order in
    which concurrent calls finish.
    """

    tag: str = "model"
    seed: int | None = None
    fail_personas: frozenset[int] = frozenset()
    script: dict[tuple[int, int], str] | None = None
    jitter: bool = False
    calls: list[Any] = Field(default_factory=list)
    _lock: Any = PrivateAttr(default_factory=threading.Lock)

    @property
    def _llm_type(self) -> str:
        return "scripted"

    def _call(self, prompt, stop=None, run_manager=None, **kwargs) -> str:
        persona = int(PERSONA_RE.search(prompt).group(1))  # the system message names it first
        item = int(QUESTION_RE.findall(prompt)[-1])  # the live question is the last one
        with self._lock:
            self.calls.append((self.seed, persona, item, prompt))
        if self.jitter:
            time.sleep(0.0004 * (zlib.crc32(prompt.encode()) % 4))
        if persona in self.fail_personas:
            raise ModelDown(f"{self.tag} cannot answer as persona {persona}")
        if self.script is not None:
            return self.script[(persona, item)]
        return hash_answer(self.tag, self.seed, prompt)


class Recorder(Callback):
    """Callback that remembers every answer in the order it is delivered."""

    def __init__(self) -> None:
        self.rows: list[tuple[Any, ...]] = []

    def save_answer(self, experiment, item_id, item, model_id, profile_id, seed, time, answer):
        self.rows.append((item_id, model_id, profile_id, seed, answer))


class LogCapture(logging.Handler):
    """Collects the records of the run loop's logger."""

    def __init__(self) -> None:
        super().__init__(level=logging.WARNING)
        self.records: list[logging.LogRecord] = []

    def emit(self, record: logging.LogRecord) -> None:
        self.records.append(record)


