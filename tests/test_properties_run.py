class TestSafeFormat:
    @PROFILE
    @given(
        values=st.dictionaries(st.sampled_from(["question", "answer_options", "name"]), any_text),
        parts=st.lists(
            st.one_of(
                st.tuples(st.just("lit"), any_text),
                st.tuples(st.just("ph"), st.sampled_from(["question", "answer_options", "name"])),
                st.tuples(st.just("ph"), st.sampled_from(["unknown", "x1"])),
            ),
            max_size=8,
        ),
    )
    def test_known_placeholders_are_filled_and_unknown_ones_stay_as_they_are(self, values, parts):
        template = template_from_parts(parts)
        # unknown placeholders come back as "{name}"; known ones as their value
        expected = "".join(
            text if kind == "lit" else (str(values[text]) if text in values else "{" + text + "}")
            for kind, text in parts
        )
        assert template.format_map(processing._SafeFormat(values)) == expected


summaries = st.builds(
    rup.RunSummary,
    n_calls=st.integers(0, 50),
    n_failed=st.integers(0, 50),
    elapsed=st.floats(0, 100, allow_nan=False),
    errors=st.lists(st.sampled_from(["a", "b", "c", "d", "e", "f", "g"]), max_size=5, unique=True),
)


def first_five_distinct(messages):
    """The oracle of how summaries merge their error messages."""
    distinct: list[str] = []
    for message in messages:
        if message not in distinct:
            distinct.append(message)
    return distinct[:5]


class TestRunSummary:
    @PROFILE
    @given(first=summaries, second=summaries)
    def test_adding_summaries_adds_the_counters_and_merges_the_errors(self, first, second):
        total = first + second
        assert total.n_calls == first.n_calls + second.n_calls
        assert total.n_failed == first.n_failed + second.n_failed
        assert total.elapsed == first.elapsed + second.elapsed
        assert total.errors == first_five_distinct(first.errors + second.errors)

    @PROFILE
    @given(first=summaries, second=summaries, third=summaries)
    def test_addition_is_associative_and_has_a_neutral_element(self, first, second, third):
        left, right = (first + second) + third, first + (second + third)
        assert (left.n_calls, left.n_failed, left.errors) == (
            right.n_calls,
            right.n_failed,
            right.errors,
        )
        neutral = first + rup.RunSummary()
        assert (neutral.n_calls, neutral.n_failed, neutral.errors) == (
            first.n_calls,
            first.n_failed,
            first.errors,
        )

    @PROFILE
    @given(summary=summaries)
    def test_derived_values_follow_the_counters(self, summary):
        assert summary.n_succeeded == summary.n_calls - summary.n_failed
        expected = f"{summary.n_calls} model calls in {summary.elapsed:.1f}s"
        if summary.n_failed:
            expected += f", {summary.n_failed} failed"
        assert str(summary) == expected


@st.composite
def memory_scenarios(draw):
    """A conversation history and the live inputs of the next question."""
    history = draw(st.lists(st.tuples(any_text, any_text), max_size=5))
    inputs = {
        "persona_description": draw(any_text),
        "general_instruction": draw(any_text),
        "question": draw(any_text),
        "answer_options": draw(any_text),
    }
    return history, inputs


class TestMemoryPrompt:
    @PROFILE
    @given(scenario=memory_scenarios())
    def test_the_history_is_inserted_literally_before_the_live_question(self, scenario):
        history, inputs = scenario
        chat = ChatPromptTemplate.from_messages(
            [("system", SYSTEM_TEMPLATE), ("user", USER_TEMPLATE)]
        )
        prompt = processing.ExperimentProcessingMixin()._memory_prompt(history, *chat.messages)

        system, human = prompt.format_messages(**inputs)
        live = (
            f"Q: {inputs['question']} | Options: {inputs['answer_options']} "
            '| A: {"answer": "<x>"} ->'
        )
        assert system.content == (
            f"You are {inputs['persona_description']}. {inputs['general_instruction']}"
        )
        assert human.content == "".join(f"{q} {a}\n" for q, a in history) + live
        assert sorted(prompt.input_variables) == sorted(inputs)

    @PROFILE
    @given(scenario=memory_scenarios())
    def test_the_string_a_plain_model_receives_is_the_two_messages(self, scenario):
        history, inputs = scenario
        chat = ChatPromptTemplate.from_messages(
            [("system", SYSTEM_TEMPLATE), ("user", USER_TEMPLATE)]
        )
        prompt = processing.ExperimentProcessingMixin()._memory_prompt(history, *chat.messages)
        system, human = prompt.format_messages(**inputs)
        assert prompt.invoke(inputs).to_string() == chat_prompt_string(
            system.content, human.content
        )


