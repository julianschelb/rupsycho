@st.composite
def grids(draw, *, failures: bool = True) -> Grid:
    """A random experiment shape: items, personas, seeds, models, option layouts, failures."""
    n_items = draw(st.integers(1, 5))
    n_personas = draw(st.integers(1, 4))
    seeds = draw(st.lists(st.integers(0, 10_000), min_size=1, max_size=3, unique=True))
    models = tuple(draw(st.lists(st.sampled_from(MODEL_IDS), min_size=1, max_size=2, unique=True)))
    item_options = tuple(
        draw(
            st.one_of(st.none(), st.tuples(st.sampled_from([", ", " | ", "\n", ""]), st.booleans()))
        )
        for _ in range(n_items)
    )
    personas = st.sets(st.integers(0, n_personas - 1), max_size=n_personas)
    failing = tuple(frozenset(draw(personas)) if failures else frozenset() for _ in models)
    return Grid(
        n_items=n_items,
        n_personas=n_personas,
        seeds=tuple(str(seed) for seed in seeds),
        models=models,
        item_options=item_options,
        failing=failing,
    )


concurrency = st.integers(1, 4)


