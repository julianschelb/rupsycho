class TestRunLoop:
    @PROFILE
    @given(grid=grids(failures=False), workers=concurrency)
    def test_a_run_makes_every_call_and_stores_every_answer(self, grid, workers):
        _, summary, _, _ = run_and_check(grid, cumulative=False, max_concurrency=workers)
        assert summary.n_failed == 0
        assert summary.n_calls == grid.n_items * grid.n_personas * len(grid.seeds) * len(
            grid.models
        )

    @PROFILE
    @given(grid=grids(), workers=concurrency)
    def test_failing_personas_are_counted_and_leave_no_rows(self, grid, workers):
        experiment, summary, _, calls = run_and_check(
            grid, cumulative=False, max_concurrency=workers
        )
        rows = experiment.get_answers_as_dataframe()
        failing_ids = {
            (grid.models[m], grid.persona_id(j))
            for m, personas in enumerate(grid.failing)
            for j in personas
        }
        assert not any(
            (r["Model ID"], r["Persona ID"]) in failing_ids for r in rows.to_dict("records")
        )
        assert len(rows) == summary.n_succeeded

    @LIGHT
    @given(grid=grids())
    def test_callbacks_and_results_do_not_depend_on_max_concurrency(self, grid):
        outcomes = []
        for workers in (1, 2, 3, 4):
            experiment, _, recorder, _ = run_and_check(
                grid, cumulative=False, max_concurrency=workers, jitter=True
            )
            outcomes.append(
                (recorder.rows, experiment.get_answers_as_dataframe().to_dict("records"))
            )
        assert all(outcome == outcomes[0] for outcome in outcomes)

    @LIGHT
    @given(grid=grids(), workers=concurrency)
    def test_cumulative_runs_follow_the_oracle_too(self, grid, workers):
        run_and_check(grid, cumulative=True, max_concurrency=workers, jitter=True)

    @LIGHT
    @given(grid=grids(), workers=concurrency, cumulative=st.booleans())
    def test_rerunning_an_experiment_gives_identical_results(self, grid, workers, cumulative):
        experiment, models = build_experiment(grid)

        def run_once():
            recorder = Recorder()
            summary = experiment.run(
                callbacks=[recorder],
                cumulative=cumulative,
                max_concurrency=workers,
                on_error="ignore",
                show_progress=False,
            )
            frame = experiment.get_answers_as_dataframe().to_dict("records")
            return recorder.rows, frame, (summary.n_calls, summary.n_failed, summary.errors)

        first, second = run_once(), run_once()
        assert first == second
        assert all(
            len(model.calls) == 2 * grid.n_items * grid.n_personas * len(grid.seeds)
            for model in models.values()
        )

        fresh, _ = build_experiment(grid)
        fresh.run(cumulative=cumulative, on_error="ignore", show_progress=False)
        assert fresh.get_answers_as_dataframe().to_dict("records") == first[1]

    @LIGHT
    @given(grid=grids(failures=False), workers=concurrency)
    def test_the_dataframe_has_one_row_per_cell_in_the_documented_order(self, grid, workers):
        experiment, _, _, _ = run_and_check(grid, cumulative=False, max_concurrency=workers)
        frame = experiment.get_answers_as_dataframe()
        cells = list(
            zip(frame["Instruction ID"], frame["Model ID"], frame["Persona ID"], frame["Run Seed"])
        )
        expected = [
            (i, model, grid.persona_id(j), seed)
            for i in range(grid.n_items)
            for model in grid.models
            for j in range(grid.n_personas)
            for seed in grid.seeds
        ]
        assert cells == expected
        assert len(set(cells)) == len(cells)


class TestCollection:
    @LIGHT
    @given(grids=st.lists(grids(), min_size=1, max_size=3), workers=concurrency)
    def test_run_all_runs_every_experiment_and_returns_one_summary_each(self, grids, workers):
        built = [build_experiment(grid) for grid in grids]
        collection = rup.ExperimentCollection([experiment for experiment, _ in built])
        summaries = collection.run_all(
            max_concurrency=workers, on_error="ignore", show_progress=False
        )
        assert len(summaries) == len(grids)
        for (experiment, _), grid, summary in zip(built, grids, summaries):
            calls = naive_run(grid, answer_function(None))
            assert (summary.n_calls, summary.n_failed) == (grid.n_calls, grid.n_failing_calls)
            assert experiment.get_answers_as_dataframe().to_dict("records") == expected_rows(
                grid, calls
            )


class TestErrorPolicy:
    @PROFILE
    @given(grid=grids())
    def test_warn_reports_failures_once_and_logs_each(self, grid):
        experiment, _ = build_experiment(grid)
        capture = LogCapture()
        logger = logging.getLogger("rupsycho.mixins.experiment_processing")
        logger.addHandler(capture)
        try:
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always")
                summary = experiment.run(show_progress=False)  # on_error="warn" is the default
        finally:
            logger.removeHandler(capture)
        runtime_warnings = [w for w in caught if issubclass(w.category, RuntimeWarning)]
        if grid.n_failing_calls:
            assert len(runtime_warnings) == 1
            assert f"{summary.n_failed} of {summary.n_calls} model calls failed" in str(
                runtime_warnings[0].message
            )
        else:
            assert runtime_warnings == []
        failures = [r for r in capture.records if "Model call failed" in r.getMessage()]
        assert len(failures) == grid.n_failing_calls

    @PROFILE
    @given(grid=grids())
    def test_ignore_is_silent(self, grid):
        experiment, _ = build_experiment(grid)
        capture = LogCapture()
        logger = logging.getLogger("rupsycho.mixins.experiment_processing")
        logger.addHandler(capture)
        try:
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always")
                summary = experiment.run(on_error="ignore", show_progress=False)
        finally:
            logger.removeHandler(capture)
        assert [w for w in caught if issubclass(w.category, RuntimeWarning)] == []
        assert capture.records == []
        assert summary.n_failed == grid.n_failing_calls

    @PROFILE
    @given(grid=grids(), workers=concurrency, cumulative=st.booleans())
    def test_raise_stops_at_the_first_failing_call(self, grid, workers, cumulative):
        experiment, models = build_experiment(grid)
        recorder = Recorder()
        calls = naive_run(grid, answer_function(None), cumulative=cumulative)
        failing = [position for position, c in enumerate(calls) if c.answer is None]

        def run():
            return experiment.run(
                callbacks=[recorder],
                cumulative=cumulative,
                max_concurrency=workers,
                on_error="raise",
                show_progress=False,
            )

        if not failing:
            run()
            assert len(recorder.rows) == len(calls)
            return
        with pytest.raises(ModelDown, match="cannot answer"):
            run()
        first = failing[0]
        # results are delivered in call order, so exactly the calls before the failure arrive
        assert len(recorder.rows) == first
        assert all(row[-1] is not None for row in recorder.rows)
        made = sum(len(model.calls) for model in models.values())
        assert made >= first + 1
        if workers == 1:
            assert made == first + 1  # nothing is asked after the failure

    @PROFILE
    @given(grid=grids(failures=False))
    def test_invalid_arguments_are_rejected_before_any_call(self, grid):
        experiment, models = build_experiment(grid)
        for kwargs in ({"on_error": "explode"}, {"max_concurrency": 0}, {"max_concurrency": -2}):
            with pytest.raises(ValueError):
                experiment.run(show_progress=False, **kwargs)
        assert all(model.calls == [] for model in models.values())


