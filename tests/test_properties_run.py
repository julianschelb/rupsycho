"""Property-based tests of the run loop, the memory-prompt helpers and seeding.

Oracle strategy
---------------
The run loop is checked against ``naive_run`` in ``tests/helpers.py``: three nested ``for``
loops that *render the prompts themselves* (string concatenation, no template engine, no shared
code) and ask a scripted model whose answer is a pure function of ``(model, seed, exact prompt)``.
Because the answer depends on the whole prompt, one comparison of the recorded answers against
the oracle proves at once that

* every (item, model, persona, seed) cell got the answer of *its* prompt - also when calls run
  concurrently and finish out of order (the model sleeps a prompt-dependent time),
* the prompts were rendered correctly, including the answers a persona remembers in cumulative
  mode and the escaping of braces, percent signs and newlines in those answers,
* callbacks, ``get_answers`` and ``get_answers_as_dataframe`` list the results in the documented
  order (callbacks: model, seed, item, persona; dataframe: item, model, persona, seed).

Grids (items 1-5, personas 1-4, seeds 1-3, models 1-2, ``max_concurrency`` 1-4) and failure
patterns (a model fails for a random subset of personas) are generated by Hypothesis.

``_escape`` and the memory-prompt builder are checked by formatting a prompt built from escaped
text back and comparing with the text. Seeding is checked on the offline tiny Hugging Face model:
equal seeds give equal samples, distinct seeds give varied ones, and the order in which seeds
are used does not matter.

Where the library violates an intended invariant, the property is written for the correct
behaviour and marked ``xfail(strict=True)`` with an ``@example`` that reproduces the bug.
"""

