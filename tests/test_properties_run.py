SEED_PROMPT = ChatPromptTemplate.from_messages([("user", "{x}")])
valid_seeds = st.integers(0, 2**32 - 1)
SEEDING = settings(PROFILE, max_examples=8)


@pytest.fixture(scope="module")
def tiny_model(tiny_hf_dir):
    """The tiny local model, loaded once for all examples of this module."""
    from rupsycho.models.model import LocalHuggingFaceModelConfig

    from .tiny_hf import TINY_PARAMETERS

    config = LocalHuggingFaceModelConfig(
        name_or_path=str(tiny_hf_dir),
        device_map="cpu",
        task="text-generation",
        parameters=dict(TINY_PARAMETERS),
    )
    return config.load_model()


def sample(model, seed, text="hello"):
    chain = SEED_PROMPT | seed_model(model, seed) | StrOutputParser()
    return chain.invoke({"x": text})


class TestSeeding:
    @SEEDING
    @given(seed=valid_seeds, text=st.text(alphabet="abc xyz", min_size=1, max_size=6))
    def test_the_same_seed_gives_the_same_sample(self, tiny_model, seed, text):
        assert sample(tiny_model, seed, text) == sample(tiny_model, seed, text)
        assert sample(tiny_model, str(seed), text) == sample(tiny_model, seed, text)  # "7" is 7

    @SEEDING
    @given(seeds=st.lists(valid_seeds, min_size=3, max_size=5, unique=True))
    def test_distinct_seeds_give_varied_samples(self, tiny_model, seeds):
        assert len({sample(tiny_model, seed) for seed in seeds}) >= 2

    @SEEDING
    @given(seeds=st.lists(valid_seeds, min_size=2, max_size=4, unique=True), data=st.data())
    def test_a_sample_does_not_depend_on_the_order_the_seeds_are_used_in(
        self, tiny_model, seeds, data
    ):
        shuffled = data.draw(st.permutations(seeds))
        forwards = {seed: sample(tiny_model, seed) for seed in seeds}
        backwards = {seed: sample(tiny_model, seed) for seed in shuffled}
        assert forwards == backwards

    @SEEDING
    @given(
        seeds=st.lists(valid_seeds, min_size=2, max_size=3, unique=True),
        repeats=st.integers(2, 3),
    )
    def test_one_chain_samples_reproducibly_however_often_it_is_invoked(
        self, tiny_model, seeds, repeats
    ):
        """The run loop builds one chain per (model, seed) and invokes it for every question."""
        chains = {
            seed: SEED_PROMPT | seed_model(tiny_model, seed) | StrOutputParser() for seed in seeds
        }
        first = {seed: chain.invoke({"x": "hello"}) for seed, chain in chains.items()}
        for _ in range(repeats):  # interleave the chains: no call may disturb another
            for seed, chain in chains.items():
                assert chain.invoke({"x": "hello"}) == first[seed]

    @SEEDING
    @given(seed=st.integers(-(2**40), 2**40))
    @example(seed=-1)
    @example(seed=2**32)
    def test_any_integer_is_a_usable_seed(self, tiny_model, seed):
        try:
            ExperimentParameters(seeds=[seed])
        except ValidationError:
            return  # a seed that is rejected up front is not used, which is also fine
        assert sample(tiny_model, seed) == sample(tiny_model, seed)
