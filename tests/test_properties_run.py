def build_experiment(grid: Grid, *, script=None, jitter: bool = False, trailing=()):
    """The experiment of ``grid`` with one scripted model per model identifier.

    ``trailing`` lists further chat messages (``{"role": ..., "content": ...}``) appended to the
    two-message prompt template.
    """
    config = build_config(grid)
    config["prompt_template"]["messages"].extend(trailing)
    experiment = rup.experiment_from_dict(config)
    models = {}
    for index, model_id in enumerate(grid.models):
        model = ScriptedLLM(
            tag=model_id, fail_personas=grid.failing[index], script=script, jitter=jitter
        )
        experiment.add_model(model, identifier=model_id)
        models[model_id] = model
    return experiment, models


def answer_function(script):
    """``answer_of`` of the oracle for a model with (or without) a script."""
    if script is None:
        return lambda model, seed, persona, item, prompt: hash_answer(model, seed, prompt)
    return lambda model, seed, persona, item, prompt: script[(persona, item)]


def expected_error_messages(grid: Grid, calls) -> list[str]:
    """The distinct failure messages in call order, as ``RunSummary.errors`` lists them."""
    messages: list[str] = []
    for call in calls:
        if call.answer is None:
            message = f"ModelDown: {grid.models[call.model_index]} cannot answer as persona {call.persona}"
            if message not in messages:
                messages.append(message)
    return messages[:5]


def run_and_check(grid: Grid, *, cumulative: bool, max_concurrency: int, script=None, jitter=False):
    """Run ``grid`` and compare everything observable with the oracle's replay."""
    experiment, models = build_experiment(grid, script=script, jitter=jitter)
    recorder = Recorder()
    summary = experiment.run(
        callbacks=[recorder],
        cumulative=cumulative,
        max_concurrency=max_concurrency,
        on_error="ignore",
        show_progress=False,
    )
    calls = naive_run(grid, answer_function(script), cumulative=cumulative)

    # counters
    assert summary.n_calls == len(calls) == grid.n_calls
    assert summary.n_failed == grid.n_failing_calls == sum(c.answer is None for c in calls)
    assert summary.n_succeeded == summary.n_calls - summary.n_failed
    assert summary.errors == expected_error_messages(grid, calls)
    assert summary.elapsed >= 0

    # every callback, in the order the calls are made (identical for any max_concurrency)
    assert recorder.rows == [
        (
            c.item,
            grid.models[c.model_index],
            grid.persona_id(c.persona),
            grid.seeds[c.seed_index],
            c.answer,
        )
        for c in calls
    ]

    # the prompts each model received
    for index, model_id in enumerate(grid.models):
        expected = [
            (int(grid.seeds[c.seed_index]), c.persona, c.item, c.prompt)
            for c in calls
            if c.model_index == index
        ]
        seen = models[model_id].calls
        assert len(seen) == len(expected) == grid.n_items * grid.n_personas * len(grid.seeds)
        if max_concurrency == 1:
            assert seen == expected  # one at a time: even the order of the calls is fixed
        else:
            assert sorted(seen) == sorted(expected)

    # what is stored: one row per answered cell, in the documented order
    assert experiment.get_answers_as_dataframe().to_dict("records") == expected_rows(grid, calls)
    assert [plain(answers) for answers in experiment.get_answers()] == expected_answers(grid, calls)
    return experiment, summary, recorder, calls


